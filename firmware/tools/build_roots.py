"""Build a compact PEM trust store from Certifi's Mozilla roots.

Use normal mbedTLS chain validation so a directly trusted GTS root can terminate
Discord's cross-signed chain without reintroducing the removed GlobalSign R1 CA.
"""
from pathlib import Path
import hashlib
import importlib.metadata
import certifi
from cryptography import x509
from cryptography.hazmat.primitives import serialization

NAMES = {'GTS Root R1', 'GTS Root R3', 'GTS Root R4',
         'ISRG Root X1', 'ISRG Root X2'}


def main():
    roots = x509.load_pem_x509_certificates(Path(certifi.where()).read_bytes())
    selected = []
    found = set()
    for root in roots:
        attrs = root.subject.get_attributes_for_oid(x509.NameOID.COMMON_NAME)
        if attrs and attrs[0].value in NAMES:
            selected.append(root.public_bytes(serialization.Encoding.PEM))
            found.add(attrs[0].value)
    if found != NAMES:
        raise SystemExit('Required root missing from current Certifi trust store')
    folder = Path(__file__).resolve().parents[1] / 'certs'
    data = b''.join(selected)
    (folder / 'roots.pem').write_bytes(data)
    (folder / 'PROVENANCE.md').write_text(
        '# TLS trust roots\n\n'
        'Generated by `tools/build_roots.py` from Certifi ' + importlib.metadata.version('certifi') + '.\n\n'
        'Roots: ' + ', '.join(sorted(found)) + '.\n\n'
        'Source: https://github.com/certifi/python-certifi (Mozilla CA roots; MPL-2.0).\n\n'
        'SHA256 roots.pem: `' + hashlib.sha256(data).hexdigest() + '`.\n\n'
        'Normal mbedTLS chain validation checks hostname, signature and validity dates. '
        'The GTS roots support Discord; ISRG roots support Steam. Roots are extracted '
        'from an existing trusted store, never trusted from a server-provided chain. '
        'A provider moving to another CA requires a trust-store update.\n', encoding='utf-8')
    print('Generated compact PEM store with', len(selected), 'trusted roots.')


if __name__ == '__main__':
    main()
